export const GENERATE_PRACTICE_PROMPT = (
  gap: string,
  topic: string,
) => `针对以下关于「${topic}」的知识缺口，生成一个主动回忆练习。

## 待补强的知识缺口
${gap}

## 练习设计原则

1. **主动回忆**：练习应要求用户主动输出（解释/作答），而非被动选择
2. **针对性**：直接对应上述知识缺口，不偏离主题
3. **循序渐进**：难度适中，既能挑战又不至于让人挫败
4. **多样化**：不同类型的缺口使用不同形式的练习

## 练习类型参考

| 缺口类型 | 推荐练习形式 |
|----------|-------------|
| concept | 用自己的话重新定义核心概念 |
| causal | 解释"为什么"，画出因果链 |
| example | 为概念想一个新的生活实例 |
| boundary | 说明该概念的适用和不适用场景 |
| transfer | 将概念类比到一个全新的领域 |

## 输出格式

\`\`\`json
{
  "practice": {
    "id": "<practice-id>",
    "type": "<explanation|choice|counter_example|analogy>",
    "prompt": "<给用户的练习提示/题目>",
    "hints": ["<提示1>", "<提示2>"],
    "answer": "<期望的理想答案或答案要点>"
  }
}
\`\`\``

