export const SOCRATIC_QUESTION_PROMPT = (
  topic: string,
  explanation: string,
  previousQa: string,
  gapHints: string,
) => `基于以下关于「${topic}」的学习材料和历史问答，生成 1-3 个最有价值的苏格拉底式追问。

## 用户的原始讲解
${explanation}

## 历史问答记录
${previousQa || '（暂无历史问答）'}

## 已识别的知识缺口线索
${gapHints || '（暂无缺口线索）'}

## 追问设计原则

1. **精准定位**：每个追问都应针对一个具体的认知盲区或浅层理解
2. **层层递进**：追问应由浅入深，先确认基础理解再挑战深层思考
3. **开放性强**：避免是非题，多用"为什么""如何""如果...会怎样"等开放式提问
4. **启发而非测试**：目的是引导思考，不是考核记忆
5. **数量适中**：1-3 个即可，质量优于数量

## 输出格式

请严格按照以下 JSON 格式输出：
\`\`\`json
{
  "questions": [
    {
      "id": "<唯一标识>",
      "content": "<追问内容>",
      "strategy": "<使用的苏格拉底策略，如：clarification/elaboration/evidence/hypothetical/perspective>",
      "target_gap": "<此问题针对的知识缺口类型: concept/causal/example/boundary/transfer>"
    }
  ]
}
\`\`\`

可选的苏格拉底策略说明：
- clarification（澄清）：要求进一步阐明模糊表述
- elaboration（深化）：要求对某一点展开更详细的解释
- evidence（求证）：要求提供证据或推理依据
- hypothetical（假设）：通过假设情境检验理解的灵活性
- perspective（视角）：要求从不同角度重新审视概念`

